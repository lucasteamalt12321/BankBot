def emperor_by_id(emperor_id: str) -> Emperor | None:
    """Возвращает императора/правителя по id или None."""
    for e in RULERS:
        if e.id == emperor_id:
            return e
    return None


def events_for_emperor(emperor_id: str) -> tuple[HistoryEvent, ...]:
    """События конкретного правителя (в порядке списка)."""
    return tuple(ev for ev in EVENTS if ev.emperor_id == emperor_id)


def persons_for_emperor(emperor_id: str) -> tuple[Person, ...]:
    """Личности конкретного правителя."""
    return tuple(p for p in PERSONS if p.emperor_id == emperor_id)
