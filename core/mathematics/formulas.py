@dataclass(frozen=True)
class MathTask:
    """Статичная задача с числовым/текстовым ответом."""

    id: str
    topic: str
    difficulty: str  # "легкая", "средняя", "сложная"
    question: str
    answer: Any
    hint: str = ""
    explanation: str = ""


