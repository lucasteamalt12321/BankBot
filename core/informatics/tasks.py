CODE_LESSON_5 = (
    "def sieve(n):\n"
    "    is_prime = [False, False] + [True] * (n - 1)\n"
    "    d = 2\n"
    "    while d * d <= n:\n"
    "        if is_prime[d]:\n"
    "            for i in range(d * d, n + 1, d):\n"
    "                is_prime[i] = False\n"
    "        d += 1\n"
    "    return is_prime\n\n"
    "# наибольший простой делитель на отрезке [l, r]\n"
    "def largest_prime_divisors(l, r):\n"
    "    largest = [0] * (r + 1)\n"
    "    d = 2\n"
    "    while d <= r:\n"
    "        if largest[d] == 0:\n"
    "            for i in range(d, r + 1, d):\n"
    "                largest[i] = d\n"
    "        d += 1\n"
    "    return [largest[x] for x in range(l, r + 1)]"
)

